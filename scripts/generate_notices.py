#!/usr/bin/env python3
"""
Generates Vimivo's third-party notices from the pinned inputs (ADR-004):

- scripts/build_media/manifest.json: the desktop media package (libmpv, FFmpeg and dependencies);
- scripts/notices/app_components.json + gradle/libs.versions.toml: libraries inside the apps.

Outputs (both committed; CI runs --check and fails when they are stale):
- shared/src/commonMain/kotlin/dev/vimivo/core/legal/ThirdPartyComponents.kt, read by About on all five apps;
- docs/THIRD_PARTY_NOTICES.md.

    python3 scripts/generate_notices.py [--check]
"""

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = json.loads((ROOT / "scripts/build_media/manifest.json").read_text())
APP = json.loads((ROOT / "scripts/notices/app_components.json").read_text())
VERSIONS = tomllib.loads((ROOT / "gradle/libs.versions.toml").read_text())["versions"]
KOTLIN_OUT = ROOT / "shared/src/commonMain/kotlin/dev/vimivo/core/legal/ThirdPartyComponents.kt"
DOC_OUT = ROOT / "docs/THIRD_PARTY_NOTICES.md"
DESKTOP = ["macos", "windows", "linux"]
PLATFORM_ENUM = {"android": "ANDROID", "ios": "IOS", "macos": "MACOS", "windows": "WINDOWS", "linux": "LINUX"}
PLATFORM_LABEL = {"android": "Android", "ios": "iOS", "macos": "macOS", "windows": "Windows", "linux": "Linux"}


def components():
    result = []
    for entry in APP["components"]:
        version = entry["version"]
        if version.startswith("toml:"):
            version = VERSIONS[version[len("toml:"):]]
        result.append({**entry, "version": version, "media": False})
    for component in MANIFEST["components"]:
        platforms = component.get("platforms", DESKTOP)
        result.append({"name": component["name"], "version": component["version"], "license": component["license"],
                       "url": component["url"], "platforms": platforms, "media": True})
        for dep in component.get("stage", []):
            if dep["shipped"]:
                result.append({"name": f"{dep['name']} (in {component['name']})", "version": dep["version"],
                               "license": dep["license"], "url": dep["url"], "platforms": platforms, "media": True})
    return result


def kotlin_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def render_kotlin(items):
    lines = [
        "// GENERATED by scripts/generate_notices.py from scripts/build_media/manifest.json,",
        "// scripts/notices/app_components.json and gradle/libs.versions.toml. Do not edit by hand.",
        '@file:Suppress("MaxLineLength", "MaximumLineLength")',
        "",
        "package dev.vimivo.core.legal",
        "",
        f"internal const val MEDIA_RELEASE: String = {kotlin_string(MANIFEST['release'])}",
        "",
        "internal val generatedComponents: List<ThirdPartyComponent> = listOf(",
    ]
    for item in items:
        platforms = [f"NoticePlatform.{PLATFORM_ENUM[p]}" for p in item["platforms"]]
        if len(platforms) == 1:
            platform_lines = [f"        platforms = setOf({platforms[0]}),"]
        else:
            platform_lines = ["        platforms = setOf(", *[f"            {p}," for p in platforms], "        ),"]
        lines += [
            "    ThirdPartyComponent(",
            f"        name = {kotlin_string(item['name'])},",
            f"        version = {kotlin_string(item['version'])},",
            f"        license = {kotlin_string(item['license'])},",
            f"        sourceUrl = {kotlin_string(item['url'])},",
            *platform_lines,
            f"        mediaPackage = {'true' if item['media'] else 'false'},",
            "    ),",
        ]
    lines += [")", ""]
    return "\n".join(lines)


def render_markdown(items):
    def table(rows):
        out = ["| Component | Version | Licence | Platforms | Source |", "|---|---|---|---|---|"]
        for item in rows:
            platforms = ", ".join(PLATFORM_LABEL[p] for p in item["platforms"])
            version = item["version"]
            if len(version) == 40 and all(c in "0123456789abcdef" for c in version):
                version = version[:12]  # a git revision
            out.append(f"| {item['name']} | {version} | {item['license']} | {platforms} | <{item['url']}> |")
        return out

    lines = [
        "# Third-party notices",
        "",
        "Generated by `scripts/generate_notices.py`; do not edit by hand. The same list is shown in About on every app.",
        "",
        "## LGPL notice",
        "",
        "Vimivo itself is MIT-licensed. The desktop apps dynamically link libmpv, FFmpeg and other libraries under the",
        "GNU Lesser General Public License 2.1 or later (ADR-004). They are built without any GPL or non-free component",
        "(`scripts/build_media/verify.py` checks this) and can be replaced by a modified build:",
        "",
        f"- Build scripts: <https://github.com/Vimivo/Player/tree/main/scripts/build_media> (release `{MANIFEST['release']}`).",
        f"- Prebuilt packages and checksums: <https://github.com/Vimivo/Player/releases/tag/{MANIFEST['release']}>.",
        "- Each component's exact source archive is listed below and pinned by SHA-256 in `manifest.json`.",
        "- Full licence texts ship inside each desktop app (`media-licenses/`).",
        "",
        "The Android app links LibVLC (LGPL-2.1-or-later) dynamically; see `docs/LICENSE_AUDIT_MOBILE.md` for its",
        "current GPL modules and the planned LGPL-only build.",
        "",
        "## Desktop media package (macOS, Windows, Linux)",
        "",
        *table([i for i in items if i["media"]]),
        "",
        "## Application libraries",
        "",
        *table([i for i in items if not i["media"]]),
        "",
    ]
    return "\n".join(lines)


def main():
    items = components()
    outputs = {KOTLIN_OUT: render_kotlin(items), DOC_OUT: render_markdown(items)}
    if "--check" in sys.argv:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text() != text]
        if stale:
            sys.exit("Stale third-party notices (run python3 scripts/generate_notices.py): " + ", ".join(stale))
        print("Third-party notices are up to date.")
        return
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
